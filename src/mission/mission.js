function renderSimilarityPlain(result) {
  const line = $('similarity-plain');
  if (!result || result.index === null) { line.textContent = 'Metrics are missing to compare the relief.'; return; }
  const comps = (result.components || []).filter((c) => finite(c.score));
  const sorted = [...comps].sort((a, b) => b.score - a.score);
  const level = result.index >= 70 ? 'high' : result.index >= 40 ? 'medium' : 'low';
  const best = sorted[0], worst = sorted.at(-1);
  line.replaceChildren(document.createTextNode('Relief resemblance: '), el('strong', '', level), document.createTextNode('.'));
  if (best) line.append(document.createTextNode(` Most similar: ${PLAIN_COMPONENT[best.key] || best.label}.`));
  if (worst && worst !== best) line.append(document.createTextNode(` Most different: ${PLAIN_COMPONENT[worst.key] || worst.label}.`));
  line.append(document.createTextNode(' It only measures terrain shape, not the environment.'));
}

