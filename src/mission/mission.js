  const em = sc.earthGrid?.metrics, tm = sc.targetGrid?.metrics;
  if (finite(em?.slopeP90Deg) && finite(tm?.slopeP90Deg) && em.slopeP90Deg > 0) {
    const r = tm.slopeP90Deg / em.slopeP90Deg;
    cards.push(plainCard('TERRAIN', r > 1.25 ? 'Steeper there' : r < 0.8 ? 'Flatter there' : 'Similar slopes',
      `Steep slopes reach ${num(em.slopeP90Deg, 0)}° here and ${num(tm.slopeP90Deg, 0)}° there.`, r > 1.25 || r < 0.8 ? 'warn' : 'good'));
  }
