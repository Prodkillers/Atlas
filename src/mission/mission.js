function latLonToVector(lat, lon, radius = 1) {
  const a = lat * Math.PI / 180, b = lon * Math.PI / 180;
  return new THREE.Vector3(Math.cos(a) * Math.cos(b) * radius, Math.sin(a) * radius, -Math.cos(a) * Math.sin(b) * radius);
}
