    const tC = th.meanK - 273.15, diff = v.temperatureC - tC;
    const range = finite(th.minK) && finite(th.maxK) ? ` (from ${num(th.minK - 273.15, 0)} to ${num(th.maxK - 273.15, 0)} °C)` : '';
